package com.arbispread.app.model

/**
 * معلومة استمرارية فرصة عملة معينة عبر آخر كذا تحديث متتالي - بتفرّق بين فرصة "ظهرت
 * لحظة واحدة واختفت" (على الأغلب خطأ سعر لحظي أو بوت هياكلها قبلك) وفرصة "مستمرة
 * فعلاً من كذا دقيقة" (أكتر ثقة إنها لسه موجودة وقت ما تدوس تنفيذ).
 *
 * **ملحوظة مهمة:** الحساب هنا بيتم على رأس مال مرجعي ثابت (مش رأس المال اللي
 * المستخدم كاتبه دلوقتي)، عشان لو المستخدم غيّر رأس المال، التاريخ متلغيش من الصفر -
 * النسبة% بتفضل نفسها تقريباً بغض النظر عن حجم رأس المال (ما عدا تأثير بسيط من رسم
 * السحب الثابت بالدولار)، فالرقم المرجعي كافٍ لتتبّع "هل الفرصة لسه موجودة؟".
 */
data class CoinPersistenceInfo(
    /** عدد التحديثات المتتالية الأخيرة اللي كانت العملة فيها رابحة - 0 لو مش رابحة دلوقتي */
    val consecutiveProfitableCount: Int,
    /** من قد ايه الفرصة دي مستمرة (بالدقايق) - من أول تحديث في السلسلة المتتالية الحالية لحد دلوقتي */
    val persistenceMinutes: Double,
) {
    companion object {
        /** رأس مال مرجعي ثابت لحساب الاستمرارية - مستقل عن رأس مال المستخدم الفعلي */
        const val REFERENCE_CAPITAL_USD = 1000.0

        /** أقل عدد تحديثات متتالية عشان نعتبر الفرصة "مستمرة فعلاً" مش مجرد ومضة لحظية */
        const val STRONG_STREAK_THRESHOLD = 3
    }
}
